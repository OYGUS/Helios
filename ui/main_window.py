"""Helios Main Desktop Window (MainWindow) — facade.

Features:
- Project Explorer grouped either by unified Project Name or by Application Source (Antigravity, OpenAI Codex, Claude Code, Codebase Analysis, Personal Projects)
- Pinned Project Core (Sun) summary card generated by the built-in deterministic analysis engine
- Optional local Ollama (`gemma3:4b`, `qwen2.5-coder`, etc.) verification and summary enhancement
- Drag-and-drop node positioning, context menus, keyboard shortcuts (ESC, Ctrl+F, Ctrl+Z/Y), and Breadcrumb navigation
- One-click switching across different sources of the same project (e.g., Antigravity <-> OpenAI Codex <-> Codebase)
- Direct workspace/source file opening and one-click 'Copy as AI Context (Prompt)' export

This module is a thin facade over the package `ui/window/`: it re-exports every name
that was importable from it before the split (classes, helpers, constants and the
names it imported), so `from ui.main_window import X` and `ui.main_window.X` keep
working. Nothing in `ui/window/` imports this module.

Module map (`ui/window/`; helpers and dialogs never import the mixins):
   * `constants`             — `DARK_STYLESHEET`, `PLANET_COLOR_PRESETS`, `SATELLITE_TAG_PRESETS`.
   * `project_text`          — purpose source labels (`purpose_source_tag`), the weak-evidence tip,
                               the project filter text, `AUTO_PURPOSE_SETTING_KEY`.
   * `ignored_folders`       — the ``ignored_folders`` setting helpers (`folder_is_ignored`, ...).
   * `open_path`             — `open_in_file_manager` (QDesktopServices; Windows, macOS, Linux).
   * `new_project_dialog`    — `NewProjectStudioDialog`.
   * `integrations`          — `IntegrationCardWidget`, `AIConnectionsView`, `AIConnectionsDialog`.
   * `remove_project_dialog` — `RemoveProjectDialog` (+ `_ChoiceButton`).
   * `settings_dialog`       — `HeliosSettingsDialog`.
   * `window`                — `HeliosMainWindow` (``__init__`` + the mixin map below).
   * `ui.window.startup` — `StartupMixin`: Startup tasks, onboarding, the integrations page switch, settings and AI controls.
   * `ui.window.store_worker` — `StoreWorkerMixin`: Busy state of store-mutating background workers and the close handshake.
   * `ui.window.history` — `HistoryMixin`: Keyboard shortcuts, undo / redo and live reload of galaxy.json.
   * `ui.window.layout` — `LayoutMixin`: Window construction and small UI helpers.
   * `ui.window.header` — `ProjectHeaderMixin`: The pinned project header (construction, refresh, the “…” menu).
   * `ui.window.purpose` — `PurposeMixin`: The project purpose block, its editor and suggestion actions.
   * `ui.window.tree` — `ProjectTreeMixin`: The left project tree.
   * `ui.window.navigation` — `NavigationMixin`: Canvas signals, breadcrumb, search, filter, export, tour and view toggles.
   * `ui.window.inspector_panel` — `InspectorMixin`: The inspector body: rendering the selection and the edit section's state.
   * `ui.window.node_edits` — `NodeEditsMixin`: Saving, deleting and adding nodes; designing a new project.
   * `ui.window.projects` — `ProjectActionsMixin`: Project-level actions: remove, merge, analyze, scan, sync, open, copy as prompt.
   * `ui.window.ollama_runs` — `OllamaMixin`: Ollama runs, automatic purpose suggestions and applying their results.

Monkeypatching: a module attribute must be patched in the module that READS it, not
here. For example the Ollama workers are read by `ui.window.ollama_runs`
(`OllamaEnhanceWorker`, `OllamaServerCheckWorker`). Patches on `HeliosMainWindow`,
the dialog classes or an instance work as before.
"""

