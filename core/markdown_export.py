"""Builds a readable Markdown architecture document from one project map (pure, no Qt).

The document contains only what the map contains:

* the project name; the purpose only when a real one exists (written by the user, taken
  from the project's own description, or an AI suggestion the user accepted) — a pending
  suggestion is never written; the identity line ("what it is", from the analysis);
* every module (title, kind, layer, entry point), its description text and its AI-written
  description, each clearly labelled, and its components with their code facts
  (kind, signature, location, defined names, calls);
* every link "A → B (kind / label)" exactly as stored, the external libraries, the entry
  points, the notes placed on the map;
* a footer saying it was generated by Helios and how the results were derived, quoting
  the analysis lines the importer stored (AST vs. pattern matching, …).

Paths are written relative to the project folder; the absolute folder path never appears.
The "Work History" module is listed only with its size: its sessions come from chat
history, not from the code. Output is deterministic (stable ordering, no timestamps).
"""

from __future__ import annotations

import re
import unicodedata
from typing import Callable, List, Optional, Sequence

from core.models import LAYER_DEFINITIONS
from core.map_facts import (
    analysis_lines,
    content_field,
    entry_note,
    link_kind,
    link_kind_label,
    relative_path,
    scrub_root,
    split_list,
)

# Purpose sources that are a real purpose (see connectors.purpose_suggestion).
REAL_PURPOSE_SOURCES = ("user", "readme", "ai")
PURPOSE_SOURCE_NOTES = {
    "user": "written by you",
    "readme": "from the project's own description",
    "ai": "an AI suggestion you accepted",
}
LAYER_NAMES = {key: title for key, (title, _color) in LAYER_DEFINITIONS.items()}
MODULE_KIND_NAMES = {
    "file": "File",
    "dir": "Folder",
    "layer": "Layer group",
    "history": "Session history",
    "external": "External libraries",
}
COMPONENT_KIND_NAMES = {
    "function": "Function",
    "class": "Class",
    "method": "Method",
    "constants": "Constants",
    "file": "File",
    "package": "Package",
    "session": "Session",
    "document": "Document",
}
FOOTER_RULES = (
    "Links come only from imports, includes and references that the analysis found in the "
    "source code; nothing is guessed. Links marked \"Added by hand\" were drawn in Helios."
)
_MD_SPECIAL = re.compile(r"([\\`*_\[\]<|#])")


def file_stem(name: str, fallback: str = "helios-map") -> str:
    """A safe, lower-case file name stem for a project name ("My App!" -> "my-app")."""
    text = unicodedata.normalize("NFKD", str(name or "")).encode("ascii", "ignore").decode("ascii")
    stem = re.sub(r"[^a-zA-Z0-9]+", "-", text).strip("-").lower()
    return stem[:60].strip("-") or fallback


def esc(text: str) -> str:
    """Escapes Markdown punctuation in plain text (names, titles, labels)."""
    return _MD_SPECIAL.sub(r"\\\1", " ".join(str(text or "").split()))


def code(text: str) -> str:
    """Inline code span that survives backticks in the text."""
    t = " ".join(str(text or "").split())
    if not t:
        return ""
    fence = "``" if "`" in t else "`"
    pad = " " if fence == "``" else ""
    return f"{fence}{pad}{t}{pad}{fence}"


def _quote(text: str) -> List[str]:
    lines = [ln.rstrip() for ln in str(text or "").strip().splitlines()]
    return [("> " + ln) if ln else ">" for ln in lines]


def _module_order(planets: Sequence[object]) -> List[object]:
    def key(p):
        kind = str(getattr(p, "kind", "") or "")
        quiet = 2 if kind == "history" else 1 if kind == "external" else 0
        return (quiet, 0 if getattr(p, "is_entry", False) else 1, str(p.title).lower(), str(p.id))
    return sorted(planets, key=key)


def _ref(ref: str) -> str:
    """"module::component" call reference -> "module › component"."""
    return code(str(ref).replace("::", " › "))


def build_markdown(system: object, identity_of: Optional[Callable[[object], str]] = None) -> str:
    """The Markdown document for `system` (see the module docstring)."""
    root = str(getattr(system, "workspace_path", "") or "")
    name = str(getattr(system, "project_name", "") or getattr(system, "name", "") or "Project")
    planets = list(getattr(system, "planets", []) or [])
    links = list(getattr(system, "links", []) or [])
    notes = list(getattr(system, "notes", []) or [])
    by_id = {p.id: p for p in planets}
    out: List[str] = [f"# {esc(name)}", ""]

    purpose = " ".join(str(getattr(system, "purpose", "") or "").split())
    source = str(getattr(system, "purpose_source", "") or "")
    if purpose and source in REAL_PURPOSE_SOURCES:
        out.append(f"**Purpose:** {esc(purpose)} _({PURPOSE_SOURCE_NOTES[source]})_")
    elif purpose and not source:
        out.append(f"**Purpose:** {esc(purpose)}")
    else:
        out.append("**Purpose:** _not written yet_")
    try:
        identity = identity_of(system) if identity_of else str(getattr(system, "identity", "") or "")
    except Exception:
        identity = str(getattr(system, "identity", "") or "")
    if identity:
        out += ["", f"**What it is:** {esc(identity)} _(from the code analysis)_"]
    n_comp = sum(len(getattr(p, "satellites", []) or []) for p in planets)
    out += ["", f"{len(planets)} modules · {n_comp} components · {len(links)} links", ""]

    # ---- entry points ---------------------------------------------------------
    entries: List[str] = []
    for p in _module_order(planets):
        inner = []
        if str(getattr(p, "kind", "")) == "dir":
            for s in p.satellites:
                note = content_field(str(getattr(s, "content", "") or ""), "Entry point")
                if note:
                    inner.append(f"- {esc(p.title)} › {esc(s.title)} — {scrub_root(note, root)}")
        if inner:
            entries += inner
        elif getattr(p, "is_entry", False):
            note = entry_note(p)
            entries.append(f"- {esc(p.title)}" + (f" — {scrub_root(note, root)}" if note else ""))
    if entries:
        out += ["## Entry points", "", *entries, ""]

    # ---- modules ----------------------------------------------------------------
    out += ["## Modules", ""]
    if not planets:
        out += ["_This project has no modules yet._", ""]
    for p in _module_order(planets):
        kind = str(getattr(p, "kind", "") or "")
        out.append(f"### {esc(p.title)}")
        out.append("")
        facts = [MODULE_KIND_NAMES.get(kind, "Module")]
        layer = str(getattr(p, "layer", "") or "")
        if layer:
            facts.append("Layer: " + LAYER_NAMES.get(layer, layer))
        if getattr(p, "is_entry", False):
            facts.append("Program starts here")
        path = relative_path(str(getattr(p, "file_path", "") or ""), root)
        if path:
            facts.append("Path: " + code(path))
        out += ["- " + " · ".join(facts), ""]
        if kind == "history":
            n = len(p.satellites)
            out += [f"_{n} session{'s' if n != 1 else ''} and documents from AI coding tools. "
                    "Not exported: they come from chat history, not from the code._", ""]
            continue
        summary = scrub_root(str(getattr(p, "summary", "") or ""), root).strip()
        if summary:
            out += ["Description (as stored on the map):", "", *_quote(summary), ""]
        ai = str(getattr(p, "ai_summary", "") or "").strip()
        if ai:
            out += ["AI-written description (local Ollama model, prose only):", "", *_quote(scrub_root(ai, root)), ""]
        sats = list(getattr(p, "satellites", []) or [])
        if sats:
            out += [f"#### Components ({len(sats)})", ""]
            for s in sats:
                out += _component_lines(s, root)
            out.append("")

    # ---- links ------------------------------------------------------------------
    out += [f"## Links ({len(links)})", ""]
    rows = []
    for link in links:
        a, b = by_id.get(link.source_planet_id), by_id.get(link.target_planet_id)
        if a is None or b is None:
            continue
        kind = link_kind_label(link_kind(link))
        label = " ".join(str(link.label or "").split())
        rows.append((a.title.lower(), b.title.lower(), label, f"- {esc(a.title)} → {esc(b.title)} ({kind} / {esc(label) or '—'})"))
    if rows:
        out += [r[3] for r in sorted(rows)]
    else:
        out.append("_No links._")
    out.append("")

    # ---- external libraries -----------------------------------------------------
    libs = []
    for p in planets:
        if str(getattr(p, "kind", "")) != "external":
            continue
        for s in p.satellites:
            line = f"- {code(s.title)}"
            spec = str(getattr(s, "signature", "") or "")
            if spec:
                line += f" {code(spec)}"
            declared = content_field(str(getattr(s, "content", "") or ""), "Declared in")
            if declared:
                line += f" — declared in {esc(declared)}"
            elif content_field(str(getattr(s, "content", "") or ""), "Declared"):
                line += " — imported but not declared in a manifest"
            libs.append((s.title.lower(), line))
    if libs:
        out += [f"## External libraries ({len(libs)})", "", *[l for _, l in sorted(libs)], ""]

    # ---- notes ------------------------------------------------------------------
    if notes:
        out += ["## Notes on the map", ""]
        for n in sorted(notes, key=lambda n: (str(n.title).lower(), str(n.id))):
            out.append(f"- **{esc(n.title)}** — {esc(n.content)}" if str(n.content or "").strip() else f"- **{esc(n.title)}**")
        out.append("")

    # ---- footer -----------------------------------------------------------------
    out += ["---", "", "_Generated by Helios from the code analysis shown on the map. " + FOOTER_RULES + "_", ""]
    how = analysis_lines(str(getattr(system, "core_plan", "") or ""))
    if how:
        out += ["How this map was made:", ""] + [f"- {esc(scrub_root(h, root))}" for h in how] + [""]
    else:
        out += ["_This map was not built by the code analysis (it was drawn or added in Helios)._", ""]
    return "\n".join(out).rstrip() + "\n"


def _component_lines(s: object, root: str) -> List[str]:
    kind = str(getattr(s, "kind", "") or "")
    content = str(getattr(s, "content", "") or "")
    head = f"- {code(s.title)}"
    kind_name = COMPONENT_KIND_NAMES.get(kind)
    if kind_name:
        head += f" — {kind_name}"
    sig = str(getattr(s, "signature", "") or "")
    if sig and sig != s.title and kind != "package":
        head += f" · {code(sig)}"
    rel = relative_path(str(getattr(s, "file_path", "") or ""), root)
    line_no = int(getattr(s, "line", 0) or 0)
    if rel:
        head += f" · {code(rel + (f':{line_no}' if line_no else ''))}"
    elif kind == "package" and sig:
        head += f" · {code(sig)}"
    lines = [head]
    defines = split_list(content_field(content, "Defines"))
    if defines and kind in ("file", "document", ""):
        lines.append("  - Defines: " + ", ".join(code(d) for d in defines))
    calls = list(getattr(s, "calls", []) or [])
    if calls:
        lines.append("  - Calls: " + ", ".join(_ref(c) for c in calls))
    called_by = list(getattr(s, "called_by", []) or [])
    if called_by:
        lines.append("  - Called by: " + ", ".join(_ref(c) for c in called_by))
    if not kind and content.strip():
        # A hand-made component: its text is what the user wrote.
        lines += ["  - Notes (as written on the map):", *["    " + q for q in _quote(scrub_root(content, root))]]
    return lines
